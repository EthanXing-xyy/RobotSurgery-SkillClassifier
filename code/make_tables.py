"""Write report/macros.tex and the LaTeX tables (English and Chinese) from results/results.json."""
from __future__ import annotations

import json

import data as D

R = json.loads((D.RESULTS_DIR / "results.json").read_text(encoding="utf-8"))
M, P, IP = R["models"], R["paired"], R["identity_probe"]
ROOT = D.PROJECT_ROOT

TAG = {"M0": "MZero", "M1": "MOne", "M2a": "MTwoA", "M2b": "MTwoB", "M2c": "MTwoC", "M3": "MThree",
       "M3b": "MThreeB", "M3c": "MThreeC", "M3d": "MThreeD", "M4": "MFour", "M5": "MFive",
       "C1": "COne", "C2": "CTwo", "C2t": "CTwoT"}
CMP = {"M1_vs_M0": "OneZero", "M3_vs_M1": "ThreeOne", "M4_vs_M1": "FourOne", "M3b_vs_M1": "ThreeBOne",
       "M3c_vs_M1": "ThreeCOne", "M3d_vs_M1": "ThreeDOne", "M5_vs_M4": "FiveFour", "M2b_vs_M0": "TwoBZero"}
BLK = {"K_simple": "KSimple", "K_texture": "KTexture", "duration": "Duration", "V_appear": "VAppear",
       "V_dyn": "VDyn", "V_flow": "VFlow"}


def f3(x):
    return f"{x:.3f}"


def f2(x):
    return f"{x:.2f}"


def sgn(x):
    return ("$+$" if x >= 0 else "$-$") + f"{abs(x):.3f}"


def pval(p, n=420):
    return f"{p:.3f}" if p >= 1 / n else f"<{1 / n:.4f}"


def macros():
    out = ["%% generated by code/make_tables.py from results/results.json -- do not edit"]
    add = lambda k, v: out.append(f"\\newcommand{{\\{k}}}{{{v}}}")
    for mid, t in TAG.items():
        m = M[mid]
        add(f"F{t}", f3(m["macro_f1"]))
        add(f"Acc{t}", f3(m["accuracy"]))
        add(f"AccPct{t}", f"{100 * m['accuracy']:.1f}")
        add(f"Lo{t}", f3(m["bootstrap_macro_f1"]["lo"]))
        add(f"Hi{t}", f3(m["bootstrap_macro_f1"]["hi"]))
        add(f"P{t}", pval(m["permutation"]["p_value"]))
        for c in D.CLASSES:
            add(f"F{c}{t}", f2(m["per_class"][c]["f1"]))
        add(f"FoldAcc{t}", f"{m['fold_accuracy_mean']:.2f}")
        add(f"FoldSd{t}", f"{m['fold_accuracy_sd']:.2f}")
        for u, v in m["per_user"].items():
            add(f"U{u}{t}", f"{round(v['accuracy'] * v['n'])}/{v['n']}")
    for k, t in CMP.items():
        p = P[k]
        add(f"D{t}", sgn(p["point"]))
        add(f"DAbs{t}", f3(abs(p["point"])))
        add(f"DLo{t}", sgn(p["lo"]))
        add(f"DHi{t}", sgn(p["hi"]))
    for k, t in BLK.items():
        add(f"Id{t}", f2(IP[k]["balanced_accuracy"]))
    ds = R["dataset"]
    add("NTrials", ds["n_trials"])
    add("DurMin", f"{ds['duration_s']['min']:.0f}")
    add("DurMax", f"{ds['duration_s']['max']:.0f}")
    add("DurMedian", f"{ds['duration_s']['median']:.0f}")
    for c in D.CLASSES:
        add(f"Dur{c}", f"{ds['duration_by_class'][c]:.0f}")
    add("NFramesOneHz", ds["video_frames_1hz_total"])
    add("NPairsTwoHz", ds["flow_pairs_2hz_total"])
    pace = R["pace"]
    add("PaceKSimple", f2(pace["K_simple"]["median_abs_r_logdur"]))
    add("PaceVDyn", f2(pace["V_dyn"]["median_abs_r_logdur"]))
    add("PaceKTexture", f2(pace["K_texture"]["median_abs_r_logdur"]))
    add("PaceVFlow", f2(pace["V_flow"]["median_abs_r_logdur"]))
    add("PaceKTextureMax", f2(pace["K_texture"]["max_abs_r_logdur"]))
    env = R["environment"]
    for k, name in [("python", "VerPython"), ("numpy", "VerNumpy"), ("scikit-learn", "VerSklearn"),
                    ("torch", "VerTorch"), ("torchvision", "VerTorchvision"), ("opencv", "VerOpencv"),
                    ("scipy", "VerScipy"), ("pandas", "VerPandas")]:
        add(name, env.get(k, "n/a"))
    # trial-level cases of K-simple (Figure fig7_cases), from the saved predictions and features
    import pandas as pd
    pr = pd.read_csv(D.RESULTS_DIR / "predictions_M1.csv").set_index("trial_id")
    dur = pd.read_csv(D.RESULTS_DIR / "features_K_simple.csv").set_index("trial_id")["duration_s"]
    for t in ("G001", "C004", "E001", "D005", "I005"):
        r = pr.loc[f"Suturing_{t}"]
        tag = "Case" + t[0] + {"0": "Zero"}.get(t[1], "") + ["Zero", "One", "Two", "Three", "Four", "Five"][int(t[3])]
        add(tag + "Dur", f"{dur[f'Suturing_{t}']:.0f}")
        add(tag + "PPred", f2(r[f"p_{r.pred}"]))
        add(tag + "PTrue", f2(r[f"p_{r.true}"]))
    for u in ("D", "E"):
        d = dur[[t for t in dur.index if t.split("_")[1][0] == u]]
        add(f"DurRange{u}", f"{d.min():.0f}--{d.max():.0f}")
    d = dur[[t for t in dur.index if t.split("_")[1][0] in "CF"]]
    add("DurRangeCF", f"{d.min():.0f}--{d.max():.0f}")
    (ROOT / "report").mkdir(parents=True, exist_ok=True)
    (ROOT / "report" / "macros.tex").write_text("\n".join(out) + "\n", encoding="utf-8")


ROWS = [  # (model id, group)
    ("M0", "req"), ("M1", "req"), ("M2a", "req"), ("M2b", "req"), ("M2c", "req"),
    ("M3", "req"), ("M3b", "req"), ("M3c", "req"), ("M3d", "req"),
    ("M4", "imp"), ("M5", "imp"),
    ("C1", "ctl"), ("C2", "ctl"), ("C2t", "ctl"),
]
NAMES = {
    "en": {"M0": "Majority class", "M1": "K-simple", "M2a": "V-appear", "M2b": "V-dyn", "M2c": "V-flow",
           "M3": "K-simple + V-dyn, late (primary)", "M3b": "K-simple + V-appear, late",
           "M3c": "K-simple + V-flow, late", "M3d": "K-simple + V-dyn, early",
           "M4": "K-simple + K-texture", "M5": "(K-simple + K-texture) + V-dyn, late",
           "C1": "Duration only", "C2": "K-simple, residualised on log duration",
           "C2t": "K-simple + K-texture, residualised"},
    "zh": {"M0": "多数类", "M1": "K-simple", "M2a": "V-appear", "M2b": "V-dyn", "M2c": "V-flow",
           "M3": "K-simple + V-dyn, 后期 (主模型)", "M3b": "K-simple + V-appear, 后期",
           "M3c": "K-simple + V-flow, 后期", "M3d": "K-simple + V-dyn, 早期",
           "M4": "K-simple + K-texture", "M5": "(K-simple + K-texture) + V-dyn, 后期",
           "C1": "仅时长", "C2": "K-simple, 对 log 时长残差化",
           "C2t": "K-simple + K-texture, 残差化"},
}
GROUPS = {"en": {"req": "Required experiment", "imp": "Focused improvement", "ctl": "Controls"},
          "zh": {"req": "必做实验", "imp": "针对性改进", "ctl": "对照实验"}}
HEAD = {"en": r"Model & ID & Macro-F1 [95\% CI] & Acc. & F1$_\mathrm{N}$ & F1$_\mathrm{I}$ & F1$_\mathrm{E}$ & $p$ \\",
        "zh": r"模型 & 编号 & Macro-F1 [95\% CI] & 准确率 & F1$_\mathrm{N}$ & F1$_\mathrm{I}$ & F1$_\mathrm{E}$ & $p$ \\"}


def main_table(lang):
    lines = [r"\begin{tabular}{@{}l l c c c c c c@{}}", r"\toprule", HEAD[lang], r"\midrule"]
    prev = None
    for mid, g in ROWS:
        if g != prev:
            if prev is not None:
                lines.append(r"\addlinespace[2pt]")
            lines.append(rf"\multicolumn{{8}}{{@{{}}l}}{{\textit{{{GROUPS[lang][g]}}}}} \\")
            prev = g
        m = M[mid]
        b = m["bootstrap_macro_f1"]
        pc = m["per_class"]
        name = NAMES[lang][mid]
        bold = mid in ("M1", "M3", "M4")
        fv = f3(m["macro_f1"])
        fv = rf"\textbf{{{fv}}}" if bold else fv
        lines.append(rf"\quad {name} & {mid} & {fv} [{f3(b['lo'])}, {f3(b['hi'])}] & {f3(m['accuracy'])} & "
                     rf"{f2(pc['N']['f1'])} & {f2(pc['I']['f1'])} & {f2(pc['E']['f1'])} & "
                     rf"{pval(m['permutation']['p_value'])} \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def paired_table(lang):
    lab = {"en": {"M1_vs_M0": "M1 $-$ M0 (kinematics vs majority)", "M3_vs_M1": "M3 $-$ M1 (adding video)",
                  "M4_vs_M1": "M4 $-$ M1 (adding motion texture)", "M3b_vs_M1": "M3b $-$ M1",
                  "M3c_vs_M1": "M3c $-$ M1", "M3d_vs_M1": "M3d $-$ M1", "M5_vs_M4": "M5 $-$ M4"},
           "zh": {"M1_vs_M0": "M1 $-$ M0 (运动学 对 多数类)", "M3_vs_M1": "M3 $-$ M1 (加入视频)",
                  "M4_vs_M1": "M4 $-$ M1 (加入运动纹理)", "M3b_vs_M1": "M3b $-$ M1",
                  "M3c_vs_M1": "M3c $-$ M1", "M3d_vs_M1": "M3d $-$ M1", "M5_vs_M4": "M5 $-$ M4"}}
    head = {"en": r"Comparison & Difference & 95\% CI & Status \\",
            "zh": r"比较 & 差值 & 95\% CI & 类型 \\"}
    st = {"en": ("pre-declared", "descriptive"), "zh": ("预先声明", "描述性")}
    lines = [r"\begin{tabular}{@{}l c c l@{}}", r"\toprule", head[lang], r"\midrule"]
    for k in ["M1_vs_M0", "M3_vs_M1", "M4_vs_M1", "M3b_vs_M1", "M3c_vs_M1", "M3d_vs_M1", "M5_vs_M4"]:
        p = P[k]
        lines.append(rf"{lab[lang][k]} & {sgn(p['point'])} & [{sgn(p['lo'])}, {sgn(p['hi'])}] & "
                     rf"{st[lang][0] if p['pre_declared'] else st[lang][1]} \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def main():
    macros()
    for lang, d in (("en", ROOT / "report" / "tables"), ("zh", ROOT / "report_zh" / "tables")):
        d.mkdir(parents=True, exist_ok=True)
        (d / "t_main.tex").write_text(main_table(lang), encoding="utf-8")
        (d / "t_paired.tex").write_text(paired_table(lang), encoding="utf-8")
    print("macros and tables written")


if __name__ == "__main__":
    main()
